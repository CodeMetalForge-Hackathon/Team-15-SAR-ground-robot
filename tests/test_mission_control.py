class StateTests(unittest.TestCase):
    def setUp(self):
        self.now = 100.0
        self.state = Coordinator(lambda: self.now)
        for node in NODES:
            self.sync(node)
        for node in NODES:
            self.sync(node)  # consume safety requests generated by other connections
        self.session = self.state.operator('claim', {})['session']
        self.op('resume')

    def sync(self, node='rover', **extra):
        return self.state.sync(node, dict(boot=node + '-boot-id', mode='SIMULATED',
                               telemetry={'ready': True}, **extra))

    def op(self, operation, **data):
        return self.state.operator(operation, dict(session=self.session, **data))

    def propose(self):
        return self.op('propose', node='rover', action='pulse', params={'direction':'w', 'power':20})['id']

    def test_approval_required_dispatch_once_and_ack_is_explicit(self):
        identifier = self.propose()
        self.assertIsNone(self.sync()['command'])
        self.op('approve', id=identifier)
        command = self.sync()['command']
        self.assertEqual(command['action'], 'pulse')
        self.assertIsNone(self.sync()['command'])
        self.sync(result={'id': identifier, 'ok':True, 'detail':'receiver acknowledged'})
        self.assertEqual(self.state.snapshot()['commands'][0]['status'], 'acknowledged')

    def test_second_operator_and_wrong_session_cannot_take_control(self):
        with self.assertRaises(Conflict):
            self.state.operator('claim', {})
        with self.assertRaises(Conflict):
            self.state.operator('resume', {'session':'wrong'})
        self.state.operator('stop', {})  # stop remains available to another authenticated operator
        self.assertTrue(self.state.paused)

    def test_operator_loss_cancels_queue_and_never_replays_motion(self):
        identifier = self.propose()
        self.op('approve', id=identifier)
        self.now += 3.1
        reply = self.sync()
        self.assertTrue(reply['paused'])
        self.assertTrue(reply['command']['safety'])
        self.assertEqual(self.state.commands[0]['status'], 'cancelled')
        self.assertIsNone(self.sync()['command'])

    def test_node_loss_halts_even_with_operator_alive(self):
        self.now += 2.1
        self.op('heartbeat')
        self.assertTrue(self.state.paused)
        self.assertIn('heartbeat lost', self.state.reason)

    def test_duplicate_agents_are_fenced(self):
        with self.assertRaises(Conflict):
            self.state.sync('rover', dict(boot='another-agent', mode='LIVE', telemetry={'ready':True}))

    def test_stale_vision_or_device_error_pauses_control(self):
        self.state.sync('jetson', dict(boot='jetson-boot-id', mode='LIVE', telemetry={'ready':False}))
        self.assertTrue(self.state.paused)
        with self.assertRaises(Conflict):
            self.op('resume')
        for node in NODES:
            self.sync(node)
        self.op('resume')
        self.state.sync('rover', dict(boot='rover-boot-id', mode='LIVE',
                        telemetry={'ready':True, 'agent_error':'temporary network loss'}))
        self.assertTrue(self.state.paused)

    def test_no_duplicate_outstanding_actions(self):
        self.propose()
        with self.assertRaises(Conflict):
            self.propose()

    def test_proposal_and_dispatch_expiry(self):
        identifier = self.propose()
        # Keep both the operator and device heartbeats fresh while proposal ages.
        for _ in range(21):
            self.now += 1
            for node in NODES:
                self.sync(node)
            self.op('heartbeat')
        with self.assertRaises(Conflict):
            self.op('approve', id=identifier)
        identifier = self.propose()
        self.op('approve', id=identifier)
        self.now += 2.01
        self.assertNotEqual((self.sync()['command'] or {}).get('action'), 'pulse')

    def test_ack_timeout_pauses_and_failed_ack_pauses(self):
        identifier = self.propose()
        self.op('approve', id=identifier)
        self.sync()
        for _ in range(6):
            self.now += 1
            for node in NODES:
                self.sync(node)
            self.op('heartbeat')
        self.assertTrue(self.state.paused)
        self.assertEqual(self.state.commands[0]['status'], 'unconfirmed')

    def test_bad_ack_cannot_ack_another_node(self):
        identifier = self.propose()
        self.op('approve', id=identifier)
        self.sync()
        self.sync('jetson', result={'id':identifier, 'ok':True})
        self.assertEqual(self.state.commands[0]['status'], 'dispatched')
        self.sync(result={'id':identifier, 'ok':False, 'detail':'motor failure'})
        self.assertTrue(self.state.paused)

    def test_action_schema_and_geofence(self):
        for node, action, params in [('rover','pulse',{'direction':'w','power':True}),
            ('rover','pulse',{'direction':'w\nSTOP','power':20}),
            ('crazyflie','move',{'x':2,'y':0,'z':0.5}),
            ('crazyflie','takeoff',{'height':float('nan')}), ('jetson','shell',{})]:
            with self.subTest(params=params), self.assertRaises(ValueError):
                validate_action(node, action, params)


class NetworkTests(unittest.TestCase):
    def setUp(self):
        self.state = Coordinator()
        self.server = make_server(self.state, TOKENS, port=0)
        self.url = f'http://127.0.0.1:{self.server.server_port}'
        self.worker = threading.Thread(target=self.server.serve_forever, kwargs={'poll_interval':0.02}, daemon=True)
        self.worker.start()

    def tearDown(self):
        self.server.shutdown()
        self.server.server_close()
        self.worker.join(2)

    def request(self, path, data=None, role='operator', extra=None):
        headers = {'Authorization':'Bearer ' + TOKENS[role], 'Content-Type':'application/json', **(extra or {})}
        request = Request(self.url + path, None if data is None else json.dumps(data).encode(), headers)
        with urlopen(request, timeout=2) as response:
            return json.load(response)

    def test_role_auth_origin_and_bad_body(self):
        with self.assertRaises(HTTPError) as error:
            self.request('/api/state', role='jetson')
        self.assertEqual(error.exception.code, 401)
        with self.assertRaises(HTTPError) as error:
            self.request('/api/nodes/rover/sync', {}, role='crazyflie')
        self.assertEqual(error.exception.code, 401)
        with self.assertRaises(HTTPError) as error:
            self.request('/api/claim', {}, extra={'Origin':'http://other.local'})
        self.assertEqual(error.exception.code, 403)
        with self.assertRaises(HTTPError) as error:
            self.request('/api/claim', [])
        self.assertEqual(error.exception.code, 400)

    def test_static_dashboard_and_security_headers(self):
        for path in ('/', '/app.js', '/style.css'):
            with urlopen(self.url + path) as response:
                self.assertEqual(response.status, 200)
                self.assertIn("frame-ancestors 'none'", response.headers['Content-Security-Policy'])
        with self.assertRaises(HTTPError):
            urlopen(self.url + '/../../.git/config')

    def test_browser_api_to_agent_to_actual_rover_tcp(self):
        from tests.test_rover_wifi import Receiver, KEY
        with tempfile.TemporaryDirectory() as directory:
            profile = Path(directory) / 'profile.json'
            profile.write_text(json.dumps({'ap_password':KEY}))
            profile.chmod(0o600)
            with Receiver() as receiver, contextlib.redirect_stdout(io.StringIO()):
                adapter = Rover('127.0.0.1', receiver.port, profile)
                agent = Agent('rover', TOKENS['rover'], self.url, adapter, 'LIVE')
                try:
                    agent.step()
                    session = self.request('/api/claim', {})['session']
                    self.request('/api/resume', {'session':session})
                    identifier = self.request('/api/propose', {'session':session, 'node':'rover',
                        'action':'pulse', 'params':{'direction':'w','power':20}})['id']
                    agent.step()
                    self.assertFalse(any(c.startswith('MOVE') for c in receiver.commands))
                    self.request('/api/approve', {'session':session,'id':identifier})
                    agent.step()
                    agent.step()
                    self.assertIn('MOVE w 20', receiver.commands)
                    state = self.request('/api/state')
                    self.assertEqual(state['commands'][0]['status'], 'acknowledged')
                    self.request('/api/stop', {})
                    agent.step()
                    deadline = time.monotonic() + 1
                    while receiver.commands[-1] != 'STOP' and time.monotonic() < deadline:
                        time.sleep(0.01)
                    self.assertEqual(receiver.commands[-1], 'STOP')
                finally:
                    adapter.close()

    def test_agent_disconnect_invokes_local_safety(self):
        adapter = Simulator('crazyflie')
        agent = Agent('crazyflie', TOKENS['crazyflie'], self.url, adapter)
        agent.step()
        adapter.execute('takeoff', {'height':0.5})
        self.server.shutdown()
        self.server.server_close()
        agent.step()
        self.assertFalse(adapter.airborne)
        self.assertIn('Error', agent.error)


class AdapterTests(unittest.TestCase):
    def test_stale_and_malformed_vision_are_not_ready(self):
        from mission_control.adapters import Jetson
        import os
        with tempfile.TemporaryDirectory() as directory:
            file = Path(directory) / 'vision.json'
            file.write_text('{"detections":[]}')
            adapter = Jetson(file)
            self.assertTrue(adapter.telemetry()['ready'])
            os.utime(file, (time.time()-5, time.time()-5))
            self.assertFalse(adapter.telemetry()['ready'])
            file.write_text('[]')
            with self.assertRaises(ValueError):
                adapter.telemetry()

    def test_round_trip_consumes_entire_command_ttl(self):
        from unittest.mock import patch
        adapter = Simulator('rover')
        agent = Agent('rover', TOKENS['rover'], 'http://127.0.0.1:1', adapter)
        agent.instance, agent.revision = 'existing-instance', 1
        reply = dict(instance='existing-instance', revision=1, lease_s=3, paused=False,
            command=dict(id='expired-command', safety=False, ttl_s=0.01,
                         action='pulse', params={'direction':'w','power':20}))
        class SlowResponse:
            def __enter__(self):
                time.sleep(0.02)
                return io.StringIO(json.dumps(reply))
            def __exit__(self, *_):
                pass
        with patch('mission_control.agent.urlopen', return_value=SlowResponse()):
            agent.step()
        self.assertFalse(agent.result['ok'])
        self.assertNotEqual(adapter.last, 'pulse')

    def test_private_credentials_created_once(self):
        with tempfile.TemporaryDirectory() as directory:
            file = Path(directory) / 'network.json'
            init_credentials(file)
            self.assertEqual(len(load_credentials(file)), 4)
            with self.assertRaises(FileExistsError):
                init_credentials(file)
            file.chmod(0o644)
            with self.assertRaises(ValueError):
                load_credentials(file)

    def test_live_drone_adapter_uses_existing_backend_and_context_landing(self):
        from crazyflie.demo_mission import FakeLink
        from unittest.mock import patch
        import types
        link = FakeLink()
        with patch('mission_control.adapters.importlib.import_module', return_value=types.SimpleNamespace(CrazyflieLink=lambda uri:link)):
            adapter = Crazyflie('guide', 'radio://test')
        adapter.safe()  # grounded startup must preserve preflight
        adapter.execute('takeoff', {'height':0.5})
        self.assertTrue(adapter.airborne)
        adapter.safe()
        self.assertIn(('land',), link.commands)
        self.assertFalse(adapter.telemetry()['ready'])
        with self.assertRaises(RuntimeError):
            adapter.execute('takeoff', {'height':0.5})


